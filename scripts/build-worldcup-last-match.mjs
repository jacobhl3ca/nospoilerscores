#!/usr/bin/env node
// Regenerates src/lib/worldcup2026-last-match.ts: the date of each 2026 World
// Cup team's last match, keyed by the /worldcup/teams/<slug> slug. The hub's
// "Popular teams" pills and each team page link to /worldcup?d=<that date>
// once the tournament is over.
//
// It walks ESPN's fifa.world scoreboard (the same feed the World Cup column
// reads) one day at a time from the opener to the final and keeps the last
// day each team appears. DATES ONLY: no scores, no winners, no round names are
// read into the output, so the committed file can never spoil a result.
//
//   node scripts/build-worldcup-last-match.mjs
//
// Exits 1 if any of the 48 teams in src/lib/worldCupTeams.ts is missing from
// the feed, or the feed names a team that list does not have.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TEAMS_FILE = join(ROOT, "src/lib/worldCupTeams.ts");
const OUT_FILE = join(ROOT, "src/lib/worldcup2026-last-match.ts");
const SCOREBOARD = "https://site.web.api.espn.com/apis/site/v2/sports/soccer/fifa.world/scoreboard";
const FIRST = "20260611";
const LAST = "20260719";

// Folds ESPN's "Türkiye" / "Curaçao" onto the ASCII names the team list uses.
const norm = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();

const teams = [...readFileSync(TEAMS_FILE, "utf8").matchAll(/\{ name: "([^"]+)", slug: "([^"]+)"/g)]
  .map(([, name, slug]) => ({ name, slug }));
if (teams.length !== 48) {
  console.error(`expected 48 teams in ${TEAMS_FILE}, parsed ${teams.length}`);
  process.exit(1);
}
const slugByName = new Map(teams.map((t) => [norm(t.name), t.slug]));

function* days(from, to) {
  const d = new Date(`${from.slice(0, 4)}-${from.slice(4, 6)}-${from.slice(6, 8)}T12:00:00Z`);
  for (;;) {
    const ymd = d.toISOString().slice(0, 10).replace(/-/g, "");
    if (ymd > to) return;
    yield ymd;
    d.setUTCDate(d.getUTCDate() + 1);
  }
}

const last = {};
const unknown = new Set();
let matches = 0;
for (const ymd of days(FIRST, LAST)) {
  const res = await fetch(`${SCOREBOARD}?dates=${ymd}`);
  if (!res.ok) throw new Error(`${ymd}: HTTP ${res.status}`);
  const data = await res.json();
  for (const ev of data.events ?? []) {
    matches++;
    for (const c of ev.competitions?.[0]?.competitors ?? []) {
      const slug = slugByName.get(norm(c.team?.displayName ?? ""));
      if (slug) last[slug] = ymd;
      else unknown.add(c.team?.displayName);
    }
  }
}

const missing = teams.filter((t) => !last[t.slug]).map((t) => t.slug);
if (unknown.size || missing.length) {
  if (unknown.size) console.error(`feed names not in worldCupTeams.ts: ${[...unknown].join(", ")}`);
  if (missing.length) console.error(`teams with no match in the feed: ${missing.join(", ")}`);
  process.exit(1);
}

const lines = teams.map((t) => `  "${t.slug}": { ymd: "${last[t.slug]}" },`);
writeFileSync(
  OUT_FILE,
  `// GENERATED by scripts/build-worldcup-last-match.mjs from ESPN's fifa.world
// scoreboard (${matches} matches, ${FIRST}..${LAST}). Do not edit by hand.
//
// The ET date of each team's last 2026 World Cup match, keyed by the
// /worldcup/teams/<slug> slug. Dates only, never a result.

export const WORLD_CUP_2026_LAST_MATCH: Record<string, { ymd: string }> = {
${lines.join("\n")}
};
`,
);
console.log(`wrote ${OUT_FILE}: ${teams.length} teams from ${matches} matches`);
